const AVAILABLE_LANGS = ['fr','en','es','de','it','pt'];
let currentLang = localStorage.getItem('cleanflick_lang') || 'fr';

function t(key) {
    return TRANSLATIONS[currentLang]?.[key] || TRANSLATIONS['fr'][key] || key;
}

function setLang(lang) {
    if (!AVAILABLE_LANGS.includes(lang)) lang = 'fr';
    currentLang = lang;
    localStorage.setItem('cleanflick_lang', lang);
    applyTranslations();
    // Re-rendre le tableau des fichiers
    if (typeof renderTable === 'function') renderTable();
    // Re-rendre l'historique si visible
    const histSection = document.getElementById('history');
    if (histSection?.classList.contains('active') && typeof loadHistory === 'function') loadHistory();
}

function cycleLang() {
    const idx = AVAILABLE_LANGS.indexOf(currentLang);
    const next = AVAILABLE_LANGS[(idx + 1) % AVAILABLE_LANGS.length];
    setLang(next);
}

function applyTranslations() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        const text = t(key);
        const icon = el.querySelector('i.mdi');

        if (icon) {
            // Supprimer tous les text nodes et spans i18n existants
            [...el.childNodes].forEach(node => {
                if (node.nodeType === Node.TEXT_NODE) node.remove();
            });
            const old = el.querySelector('.i18n-text');
            if (old) old.remove();
            // Ajouter le texte dans un span dédié après l'icône
            const span = document.createElement('span');
            span.className = 'i18n-text';
            span.textContent = text;
            el.appendChild(span);
        } else {
            el.textContent = text;
        }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
    });

    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        el.title = t(el.getAttribute('data-i18n-title'));
    });

    const LANG_LABELS = { fr: 'FR', en: 'EN', es: 'ES', de: 'DE', it: 'IT', pt: 'PT' };
    const btn = document.getElementById('lang-switch');
    if (btn) btn.textContent = LANG_LABELS[currentLang] || currentLang.toUpperCase();

    if (typeof updateLibFilterButton === 'function') updateLibFilterButton();
}
